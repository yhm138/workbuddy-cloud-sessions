"use strict";

/**
 * 构建静态数据：
 *   ui/data.js          会话列表快照（侧栏首屏，几十 KB）
 *   ui/full/<id>.js     单会话正文分片（点开才加载）
 *   ui/full/index.js    分片索引（哪些会话有正文、各多少条）
 *   ui/full/_search.js  全文搜索索引（标题 + 正文摘要）
 *
 * 为什么用 JS 分片而不是 JSON + fetch：
 *   扩展 iframe 以 file:// 加载页面时 fetch/XHR 会被 CORS 拦，
 *   但 <script src> 不受限制，所以把数据包成给 window 赋值的脚本最稳。
 */

const fs = require("fs");
const path = require("path");
const { UI_DIR, FULL_DIR, SESSIONS_JSON, ORIGIN_LABEL, ORIGIN_ORDER } = require("./config");
const { listCloudSessions } = require("./db");
const { readStore } = require("./fetch");

const SEARCH_SNIPPET = 200;

/** 赋值形式：window.X = {...};  （列表 / 索引这类「一次读取」的数据） */
function assign(name, obj) {
  return `window.${name}=${JSON.stringify(obj)};\n`;
}

/** 回调形式：window.X({...});  （正文分片，页面可能晚于加载注册回调） */
function jsonp(fn, obj) {
  return `${fn}(${JSON.stringify(obj)});\n`;
}

function pad(n) {
  return n < 10 ? "0" + n : String(n);
}

function stamp(ms) {
  const d = new Date(ms || Date.now());
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(
    d.getMinutes()
  )}`;
}

/** 列表来源：DB 优先（完整），DB 不可用则退回抓取结果 */
function resolveList(storeItems) {
  try {
    const list = listCloudSessions();
    if (list.length) return list;
  } catch (e) {
    console.warn(`读取本地 DB 失败，改用抓取结果：${e.message}`);
  }
  return storeItems.map((it) => ({
    id: it.id,
    title: it.title || "(无标题)",
    origin: it.origin || "unknown",
    originLabel: ORIGIN_LABEL[it.origin] || "未知来源",
    ts: it.ts || it.fetchedAt || 0,
    created: it.created || 0,
    status: it.status || "",
  }));
}

function build() {
  const store = readStore();
  if (!store.items || !store.items.length) {
    throw new Error(`没有抓取结果（${SESSIONS_JSON}）。先跑：node bin/wbcs.js fetch`);
  }
  const byId = new Map(store.items.map((it) => [it.id, it]));
  const list = resolveList(store.items);

  fs.mkdirSync(UI_DIR, { recursive: true });
  fs.rmSync(FULL_DIR, { recursive: true, force: true });
  fs.mkdirSync(FULL_DIR, { recursive: true });

  const items = [];
  const counts = {};
  const shards = [];
  const search = [];
  let shardBytes = 0;
  let searchBytes = 0;

  for (const meta of list) {
    const rec = byId.get(meta.id);
    const origin = meta.origin || "unknown";
    counts[origin] = (counts[origin] || 0) + 1;

    const msgs = (rec && rec.ok && rec.messages) || [];
    const stats = (rec && rec.stats) || { total: msgs.length, user: 0, assistant: 0, thought: 0, tool: 0 };

    items.push({
      id: meta.id,
      title: (rec && rec.title) || meta.title,
      origin,
      originLabel: ORIGIN_LABEL[origin] || "未知来源",
      ts: meta.ts || (rec && rec.fetchedAt) || 0,
      created: meta.created || 0,
      status: meta.status || "",
      n: stats.total,
      t: stats.tool || 0,
      ok: !!(rec && rec.ok),
    });

    if (!rec) continue;

    // 正文分片（ok 或明确失败都写，好让 UI 区分「没缓存」和「云端就是空的」）
    const shard = {
      id: meta.id,
      title: (rec && rec.title) || meta.title,
      origin,
      ok: !!rec.ok,
      error: rec.error || "",
      count: msgs.length,
      stats,
      messages: msgs.map((m) => [
        m.r ? m.r[0] : "a", // u / a / t / h
        m.t || "",
        m.k || "",
        m.n || "",
        m.s || "",
        m.i || "",
        m.o || "",
      ]),
    };
    const js = jsonp("window.__WBCS_SESSION__", shard);
    const buf = Buffer.from(js, "utf8");
    fs.writeFileSync(path.join(FULL_DIR, `${meta.id}.js`), buf);
    shardBytes += buf.length;
    shards.push({ id: meta.id, n: msgs.length, b: buf.length, ok: !!rec.ok });

    // 搜索索引：只收正文类消息，每条截断
    const entries = [];
    msgs.forEach((m, idx) => {
      const r = m.r ? m.r[0] : "a";
      if (r === "t") return; // 工具调用的输入输出不进搜索索引（噪音大、体积大）
      const text = String(m.t || "").replace(/\s+/g, " ").slice(0, SEARCH_SNIPPET);
      if (text.length < 2) return;
      entries.push([idx, r, text]);
    });
    if (entries.length) search.push([meta.id, entries]);
    searchBytes += JSON.stringify(entries).length;
  }

  const payload = {
    generatedAt: stamp(store.generatedAt),
    generatedAtMs: store.generatedAt || Date.now(),
    total: items.length,
    counts,
    originLabels: ORIGIN_LABEL,
    originOrder: ORIGIN_ORDER,
    webOrigin: "https://www.workbuddy.cn",
    items,
  };

  fs.writeFileSync(
    path.join(UI_DIR, "data.js"),
    "// generated by workbuddy-cloud-sessions — do not edit\n" + assign("CLOUD_SESSIONS", payload),
    "utf8"
  );

  fs.writeFileSync(
    path.join(FULL_DIR, "index.js"),
    assign("__WBCS_INDEX__", {
      generatedAt: store.generatedAt || Date.now(),
      total: shards.length,
      bytes: shardBytes,
      items: shards,
    }),
    "utf8"
  );

  fs.writeFileSync(
    path.join(FULL_DIR, "_search.js"),
    assign("__WBCS_SEARCH__", { generatedAt: store.generatedAt || Date.now(), items: search }),
    "utf8"
  );

  const okCount = shards.filter((s) => s.ok).length;
  console.log(`列表：${items.length} 条（${JSON.stringify(counts)}）`);
  console.log(`正文：${okCount}/${shards.length} 条有内容，${(shardBytes / 1024 / 1024).toFixed(1)} MB`);
  console.log(`搜索索引：${search.length} 条会话，${(searchBytes / 1024 / 1024).toFixed(1)} MB`);
  console.log(`输出：${UI_DIR}`);
  return { items, shards, payload };
}

module.exports = { build, stamp };
